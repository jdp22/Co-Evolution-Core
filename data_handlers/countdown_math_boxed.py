"""CountdownMathBoxed dataset handler.

For Math-series models (e.g. Qwen2.5-Math-*) that naturally emit \\boxed{expr}.
Uses the same countdown arithmetic data but with \\boxed{}-oriented prompts.

Corresponding data lives in:
  baseline/data/countdown_math_boxed/train.parquet
  baseline/data/countdown_math_boxed/test.parquet

Generated by:  baseline/make_countdown_math_boxed_data.py
"""
import re
from typing import Dict, List, Optional, Tuple

from utils.reward_score import countdown_boxed as reward_fn

from .base import DatasetHandler

# ---------------------------------------------------------------------------
# Prompt constants (mirrors make_countdown_math_boxed_data.py)
# ---------------------------------------------------------------------------
SYSTEM = (
    "Please reason step by step, and put your final arithmetic expression inside \\boxed{}. "
    "The expression must use each of the given numbers exactly once with +, -, *, / and parentheses only."
)

_FORMULA_ALLOWED = re.compile(r"^[0-9+\-*/() ]+$")
_NUMERIC_TOL = 1e-9


class CountdownMathBoxedHandler(DatasetHandler):
    """Countdown handler for Math-series models that output \\boxed{expr}."""

    name = "countdown_math_boxed"
    default_train_path = "baseline/data/countdown_math_boxed/train.parquet"
    default_test_path  = "baseline/data/countdown_math_boxed/test.parquet"
    default_max_tokens = 1024

    # -------------------------------------------------------------------------
    # Data loading
    # -------------------------------------------------------------------------

    def load_data(
        self,
        path: str,
        split: str = "train",
        max_samples: Optional[int] = None,
        start_index: int = 0,
    ) -> List[Dict]:
        import pandas as pd
        df = pd.read_parquet(path)
        task_datas = []
        for i, (_, row) in enumerate(df.iterrows()):
            if i < start_index:
                continue
            gt = row["reward_model"]["ground_truth"]
            numbers = [int(n) for n in gt["numbers"]]
            target  = float(gt["target"])
            messages = [{"role": m["role"], "content": m["content"]} for m in row["prompt"]]
            task_datas.append({
                "messages":     messages,
                "ground_truth": {"numbers": numbers, "target": target},
                "numbers":      numbers,
                "target":       target,
            })
            if max_samples and len(task_datas) >= max_samples:
                break
        return task_datas

    # -------------------------------------------------------------------------
    # Reward / correctness
    # -------------------------------------------------------------------------

    def compute_reward(self, response: str, ground_truth) -> float:
        return reward_fn.compute_score(response, ground_truth)

    def is_answer_correct(self, response: str, ground_truth) -> bool:
        return reward_fn.is_answer_correct(response, ground_truth)

    # -------------------------------------------------------------------------
    # Answer extraction
    # -------------------------------------------------------------------------

    def extract_answer(self, response: str) -> str:
        """Return content of last \\boxed{} or empty string."""
        return reward_fn.extract_boxed(response) or ""

    def extract_answer_for_voting(
        self,
        response: str,
        numbers: Optional[list] = None,
        debug: bool = False,
    ) -> Tuple[str, bool, Optional[Dict]]:
        """Extract \\boxed{expr}, validate numbers, evaluate to numeric result.

        Returns (numeric_result_str, is_valid, reject_info) — same contract as
        CountdownHandler.extract_answer_for_voting so majority-vote logic is reusable.
        """
        content = self.extract_answer(response)
        if not content:
            return "", False, {"reason": "no_boxed", "formula": ""}

        if not _FORMULA_ALLOWED.match(content):
            return "", False, {"reason": "invalid_chars", "formula": content[:100]}

        used = [int(n) for n in re.findall(r"\d+", content)]
        is_valid = False
        if numbers is not None:
            is_valid = sorted(used) == sorted([int(n) for n in numbers])

        try:
            result = eval(content, {"__builtins__": None}, {})  # noqa: S307
            if abs(result - round(result)) < _NUMERIC_TOL:
                result_str = str(int(round(result)))
            else:
                result_str = str(result)

            if not is_valid:
                return result_str, False, {
                    "reason": "wrong_numbers",
                    "formula": content[:100],
                    "expected": sorted(numbers) if numbers else None,
                    "got": sorted(used),
                    "result": result_str,
                }
            return result_str, True, None
        except Exception as e:
            return "", False, {"reason": "eval_error", "formula": content[:100], "error": str(e)}

    # -------------------------------------------------------------------------
    # Formatting
    # -------------------------------------------------------------------------

    def format_answer_for_check(self, answer: str) -> str:
        return f"\\boxed{{{answer}}}"

    def is_voted_answer_correct(self, voted_answer: str, ground_truth: dict) -> bool:
        """voted_answer is already a numeric string; compare to target."""
        target = float(ground_truth["target"])
        try:
            return abs(float(voted_answer) - target) < 1e-5
        except (ValueError, TypeError):
            return False

    def get_target_for_comparison(self, ground_truth) -> str:
        target = ground_truth["target"] if isinstance(ground_truth, dict) else ground_truth
        t = float(target)
        return str(int(round(t))) if abs(t - round(t)) < _NUMERIC_TOL else str(t)
